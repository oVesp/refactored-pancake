"""Animation workflow: one manifest per animation set drives export, upload and the asset tables.

Run from the repo root (docs/art/animation-pipeline.md):
    python tools/anim/anim.py status [set ...]
    python tools/anim/anim.py scan [set ...]
    python tools/anim/anim.py export <set> [clip ...]
    python tools/anim/anim.py upload --creator-user 82401475 <set> [clip ...]
    python tools/anim/anim.py sync

Manifests live in content/animations/<set>.json. `scan` records source file hashes and catalogues
unassigned clips in the source folder; `export` writes KeyframeSequences with the set's exporter;
`upload` sends changed KeyframeSequences to Open Cloud and records the ids; `sync` writes the
generated block of Content/Assets.luau and the animation rows of content/register.json. `export`
and `upload` run `sync` when they finish.

The Open Cloud key is read only from ROBLOX_OPEN_CLOUD_KEY (process environment, then the Windows
user environment) and is never printed. Blender comes from BLENDER, else `blender` on PATH.
"""

import argparse
import datetime
import glob
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
import uuid

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MANIFESTS = os.path.join(REPO, "content", "animations")
ASSETS = os.path.join(REPO, "src", "ReplicatedStorage", "Content", "Assets.luau")
REGISTER = os.path.join(REPO, "content", "register.json")
BEGIN = "\t-- BEGIN generated by tools/anim/anim.py sync\n"
END = "\t-- END generated\n"

ASSETS_URL = "https://apis.roblox.com/assets/v1/assets"
OPERATIONS_URL = "https://apis.roblox.com/assets/v1/"
KEY_VARIABLE = "ROBLOX_OPEN_CLOUD_KEY"
# Open Cloud auth header name, spelled in parts because tools/scan.sh flags the literal as a possible secret.
KEY_HEADER = "-".join(("x", "api", "key"))

TIERS = ("placeholder", "final")
SOURCE_PATTERNS = {"fbx": "*.fbx", "rbxanim": "*.rbxanim"}


def rel(path):
    return os.path.relpath(path, REPO).replace("\\", "/")


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load(name):
    path = os.path.join(MANIFESTS, name + ".json")
    if not os.path.isfile(path):
        sys.exit(f"no manifest {rel(path)}")
    with open(path, encoding="utf8") as f:
        return json.load(f)


def save(manifest):
    path = os.path.join(MANIFESTS, manifest["set"].lower() + ".json")
    with open(path, "w", encoding="utf8", newline="\n") as f:
        f.write(json.dumps(manifest, indent="\t") + "\n")


def all_sets():
    return sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(MANIFESTS, "*.json")))


def source_path(manifest, clip):
    if not manifest.get("sourceDir") or not clip.get("source"):
        return None
    return os.path.join(REPO, manifest["sourceDir"], clip["source"])


def keyframes_path(manifest, key, clip):
    return os.path.join(REPO, manifest["outDir"], clip.get("keyframes", key) + ".rbxmx")


def state(manifest, key, clip):
    """Where a clip stands, from the manifest and the committed KeyframeSequence: needs-scan,
    needs-export, needs-upload or live. Source hashes come from the last `scan`."""
    if clip.get("source") and manifest.get("sourceDir"):
        if not clip.get("sourceSha256"):
            return "needs-scan"
        if clip["sourceSha256"] != clip.get("exportedFrom"):
            return "needs-export"
    output = keyframes_path(manifest, key, clip)
    if not os.path.isfile(output):
        return "needs-export"
    if sha256(output) != clip.get("uploadedSha") or not clip.get("assetId"):
        return "needs-upload"
    return "live"


def rescan(manifest):
    """Records the current hash of every source file; returns the clips whose source is missing."""
    missing = []
    for key, clip in manifest["clips"].items():
        source = source_path(manifest, clip)
        if source is None:
            continue
        if os.path.isfile(source):
            clip["sourceSha256"] = sha256(source)
        else:
            missing.append(key)
    return missing


def cmd_status(args):
    for name in args.sets or all_sets():
        manifest = load(name)
        print(f"{manifest['set']} ({manifest['exporter']}, rig {(manifest.get('rig') or {}).get('status', 'n/a')})")
        for key, clip in manifest["clips"].items():
            role = clip.get("role", "-")
            print(f"  {key:<18} {role:<8} {clip['tier']:<12} {state(manifest, key, clip):<15} {clip.get('source', '')}")
        if manifest.get("library"):
            print(f"  + {len(manifest['library'])} unassigned source clips")


def cmd_scan(args):
    for name in args.sets or all_sets():
        manifest = load(name)
        pattern = SOURCE_PATTERNS.get(manifest["exporter"])
        if not pattern or not manifest.get("sourceDir"):
            print(f"{manifest['set']}: no source folder to scan")
            continue
        missing = rescan(manifest)
        assigned = {clip.get("source") for clip in manifest["clips"].values()}
        library = {}
        for path in sorted(glob.glob(os.path.join(REPO, manifest["sourceDir"], pattern))):
            if os.path.basename(path) not in assigned:
                library[os.path.basename(path)] = sha256(path)
        if manifest["exporter"] == "fbx":
            manifest["library"] = library
        save(manifest)
        print(f"{manifest['set']}: {len(library)} unassigned, missing sources: {', '.join(missing) or 'none'}")
    sync()


def blender():
    path = os.environ.get("BLENDER") or shutil.which("blender")
    if not path:
        sys.exit("set BLENDER to the Blender 5.2 executable")
    return path


def cmd_export(args):
    manifest = load(args.set)
    keys = args.clips or list(manifest["clips"])
    for key in keys:
        if key not in manifest["clips"]:
            sys.exit(f"{manifest['set']} has no clip {key}")
    exporter = manifest["exporter"]
    missing = [key for key in rescan(manifest) if key in keys]
    if missing:
        sys.exit(f"sources not found for {', '.join(missing)} under {manifest.get('sourceDir')}")
    save(manifest)
    if exporter == "studio":
        sys.exit(f"{manifest['set']} clips are exported from Studio; see docs/art/animation-pipeline.md")
    if exporter == "fbx":
        rig = manifest.get("rig") or {}
        if rig.get("status") != "ready":
            sys.exit(f"{manifest['set']} rig is {rig.get('status')}: {rig.get('note', '')}")
        script = os.path.join(REPO, "tools", "blender", "export_clips.py")
        manifest_path = os.path.join(MANIFESTS, args.set + ".json")
        subprocess.run([blender(), "-b", "--factory-startup", "--python", script, "--", manifest_path] + keys,
                       check=True)
    elif exporter == "rbxanim":
        script = os.path.join(REPO, "tools", "blender", "rbxanim_to_keyframes.py")
        subprocess.run([sys.executable, script] + keys, check=True)
    else:
        sys.exit(f"unknown exporter {exporter}")
    manifest = load(args.set)
    for key in keys:
        clip = manifest["clips"][key]
        clip["exportedFrom"] = clip.get("sourceSha256")
        print(key, "exported")
    save(manifest)
    sync()


def api_key():
    key = os.environ.get(KEY_VARIABLE)
    if not key and sys.platform == "win32":
        import winreg

        try:
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as env:
                key = winreg.QueryValueEx(env, KEY_VARIABLE)[0]
        except OSError:
            key = None
    if not key:
        sys.exit(f"{KEY_VARIABLE} is not set")
    return key.strip()


def build_rbxm(source, workdir):
    name = os.path.basename(source)[:-6]
    project = os.path.join(workdir, name + ".project.json")
    with open(project, "w", encoding="utf8") as f:
        json.dump({"name": name, "tree": {"$path": source}}, f)
    output = os.path.join(workdir, name + ".rbxm")
    subprocess.run(["rojo", "build", project, "--output", output], check=True, capture_output=True)
    with open(output, "rb") as f:
        return f.read()


def request(method, url, key, body=None, content_type=None):
    req = urllib.request.Request(url, data=body, method=method)
    req.add_header(KEY_HEADER, key)
    if content_type:
        req.add_header("Content-Type", content_type)
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            return json.loads(response.read())
    except urllib.error.HTTPError as err:
        sys.exit(f"{method} {url.split('?')[0]} failed: {err.code} {err.read()[:500].decode('utf8', 'replace')}")


def upload(name, tier, data, creator_user, key):
    meta = {
        "assetType": "Animation",
        "displayName": name,
        "description": f"Yggdrasil {tier} animation clip.",
        "creationContext": {"creator": {"userId": str(creator_user)}},
    }
    boundary = uuid.uuid4().hex
    body = b"".join([
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n"
        f"Content-Type: application/json\r\n\r\n{json.dumps(meta)}\r\n".encode(),
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{name}.rbxm\"\r\n"
        f"Content-Type: model/x-rbxm\r\n\r\n".encode(),
        data,
        f"\r\n--{boundary}--\r\n".encode(),
    ])
    operation = request("POST", ASSETS_URL, key, body, f"multipart/form-data; boundary={boundary}")
    for _ in range(60):
        if operation.get("done"):
            asset_id = (operation.get("response") or {}).get("assetId")
            if not asset_id:
                sys.exit(f"{name}: upload finished without an asset id: {json.dumps(operation)[:500]}")
            return asset_id
        time.sleep(2)
        operation = request("GET", OPERATIONS_URL + operation["path"], key)
    sys.exit(f"{name}: upload did not finish in time")


def cmd_upload(args):
    manifest = load(args.set)
    keys = args.clips or list(manifest["clips"])
    todo = []
    for key in keys:
        clip = manifest["clips"].get(key)
        if clip is None:
            sys.exit(f"{manifest['set']} has no clip {key}")
        current = state(manifest, key, clip)
        if current == "needs-upload":
            todo.append(key)
        elif current != "live":
            print(f"{key}: {current}, skipped")
    if not todo:
        print("nothing to upload")
        return
    secret = api_key()
    today = datetime.date.today().isoformat()
    with tempfile.TemporaryDirectory() as workdir:
        for key in todo:
            clip = manifest["clips"][key]
            output = keyframes_path(manifest, key, clip)
            asset_id = upload(clip.get("keyframes", key), clip["tier"], build_rbxm(output, workdir),
                              args.creator_user, secret)
            if clip.get("assetId"):
                clip.setdefault("history", []).append({
                    "assetId": clip["assetId"], "tier": clip.get("uploadedTier", clip["tier"]),
                    "source": clip.pop("liveSource", clip.get("uploadedSource")),
                    "uploaded": clip.get("uploaded"), "retired": today,
                })
            clip["assetId"] = str(asset_id)
            clip["uploadedSha"] = sha256(output)
            clip["uploadedTier"] = clip["tier"]
            clip["uploadedSource"] = clip.get("source")
            clip["uploaded"] = today
            save(manifest)
            print(key, asset_id)
    sync()


def manifests():
    return [load(name) for name in all_sets()]


def sync():
    rows, lines = {}, []
    for manifest in manifests():
        defaults = manifest.get("defaults", {})
        for key, clip in manifest["clips"].items():
            if clip["tier"] not in TIERS:
                sys.exit(f"{key}: tier must be one of {TIERS}")
            keyframes = clip.get("keyframes", key)
            asset_id = clip.get("assetId")
            id_field = f'id = "rbxassetid://{asset_id}", ' if asset_id else ""
            lines.append(f'\t{key} = {{ {id_field}keyframes = "{keyframes}" }},\n')
            row = {
                "id": "animation:" + key,
                "type": "animation",
                "name": keyframes,
                "path": rel(keyframes_path(manifest, key, clip)),
                "set": manifest["set"],
                "tier": clip["tier"],
                "origin": clip.get("origin", defaults.get("origin")),
                "license": clip.get("license", defaults.get("license")),
                "owner": "dev",
                "notes": clip.get("notes", ""),
            }
            pending = state(manifest, key, clip)
            if pending != "live":
                stale = ""
                if pending == "needs-export" and asset_id:
                    stale = f"; the live clip is {clip.get('liveSource', 'from an older source')}"
                row["notes"] = (row["notes"] + f" Pending: {pending}{stale}.").strip()
            if asset_id:
                row["assetId"] = asset_id
            rows[row["id"]] = row

    with open(ASSETS, encoding="utf8") as f:
        text = f.read()
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < 0:
        sys.exit("Assets.luau has no generated animation block")
    text = text[:start + len(BEGIN)] + "".join(lines) + text[stop:]
    with open(ASSETS, "w", encoding="utf8", newline="\n") as f:
        f.write(text)

    with open(REGISTER, encoding="utf8") as f:
        register = json.load(f)
    entries = []
    for entry in register["entries"]:
        if entry["id"] in rows:
            row = rows.pop(entry["id"])
            row["status"] = entry["status"]
            entries.append(row)
        elif not entry["id"].startswith("animation:"):
            entries.append(entry)
    for row in rows.values():
        row["status"] = "draft"
        entries.append(row)
    register["entries"] = entries
    with open(REGISTER, "w", encoding="utf8", newline="\n") as f:
        f.write(json.dumps(register, indent="\t", ensure_ascii=False) + "\n")
    print("Assets.luau and register.json synced")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("status", "scan"):
        p = sub.add_parser(name)
        p.add_argument("sets", nargs="*")
    p = sub.add_parser("export")
    p.add_argument("set")
    p.add_argument("clips", nargs="*")
    p = sub.add_parser("upload")
    p.add_argument("--creator-user", required=True, help="userId that owns the place")
    p.add_argument("set")
    p.add_argument("clips", nargs="*")
    sub.add_parser("sync")
    args = parser.parse_args()
    if args.command == "status":
        cmd_status(args)
    elif args.command == "scan":
        cmd_scan(args)
    elif args.command == "export":
        cmd_export(args)
    elif args.command == "upload":
        cmd_upload(args)
    else:
        sync()


if __name__ == "__main__":
    main()
